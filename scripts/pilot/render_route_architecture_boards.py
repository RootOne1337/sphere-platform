from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

OUT = Path("docs/audits/2026-10-27/route-architecture-boards")
FONT = Path("C:/Windows/Fonts/segoeui.ttf")
BOLD = Path("C:/Windows/Fonts/segoeuib.ttf")


def font(size, bold=False):
    return ImageFont.truetype(str(BOLD if bold else FONT), size)


def arrow(draw, a, b, color="#526983"):
    import math

    draw.line((a, b), fill=color, width=4)
    angle = math.atan2(b[1] - a[1], b[0] - a[0])
    left = (b[0] - 14 * math.cos(angle - 0.52), b[1] - 14 * math.sin(angle - 0.52))
    right = (b[0] - 14 * math.cos(angle + 0.52), b[1] - 14 * math.sin(angle + 0.52))
    draw.polygon((b, left, right), fill=color)


def board(filename, title, subtitle, items, footer, *, feedback=False, recovery=False):
    image = Image.new("RGB", (1800, 1110), "#0b111d")
    d = ImageDraw.Draw(image)
    for y in range(1110):
        if y % 4 == 0:
            d.line((0, y, 1800, y), fill="#0d1421")
    d.rounded_rectangle((65, 42, 1735, 1068), radius=30, fill="#101a29", outline="#25364d", width=2)
    d.text((105, 71), "SPHERE  /  ROUTE LAB", font=font(18, True), fill="#81e5cb")
    d.text((105, 108), title, font=font(44, True), fill="#f2f6fd")
    d.text((107, 174), subtitle, font=font(22), fill="#9aacbf")
    d.line((105, 220, 1695, 220), fill="#293c53", width=2)
    boxes = [
        (105, 265, 595, 515),
        (655, 265, 1145, 515),
        (1205, 265, 1695, 515),
        (1205, 620, 1695, 870),
        (655, 620, 1145, 870),
        (105, 620, 595, 870),
    ]
    for i, (box, item) in enumerate(zip(boxes, items), 1):
        x1, y1, x2, y2 = box
        tag, name, lines, color = item
        d.rounded_rectangle(box, radius=20, fill="#152337", outline="#304862", width=2)
        d.ellipse((x1 + 22, y1 + 22, x1 + 62, y1 + 62), fill=color)
        d.text((x1 + 35, y1 + 24), str(i), font=font(19, True), fill="#0b1523")
        d.text((x1 + 78, y1 + 25), tag.upper(), font=font(15, True), fill=color)
        d.text((x1 + 24, y1 + 78), name, font=font(27, True), fill="#f4f7fc")
        for j, line in enumerate(lines):
            d.text((x1 + 25, y1 + 127 + j * 29), line, font=font(20), fill="#b5c4d5")
    for a, b in (
        ((595, 390), (645, 390)),
        ((1145, 390), (1195, 390)),
        ((1450, 520), (1450, 610)),
        ((1205, 745), (1155, 745)),
        ((655, 745), (605, 745)),
    ):
        arrow(d, a, b)
    if feedback:
        d.line(((105, 745), (83, 745), (83, 390), (105, 390)), fill="#70dfbf", width=3)
        arrow(d, (83, 390), (103, 390), "#70dfbf")
    if recovery:
        d.text((1472, 554), "если не удалось", font=font(16), fill="#aabed0")
        d.text((490, 590), "только при подтверждённых условиях", font=font(15), fill="#aabed0")
    d.rounded_rectangle(
        (105, 925, 1695, 1024), radius=15, fill="#101d2b", outline="#2e5364", width=2
    )
    d.text((128, 942), "ГРАНИЦА ПРОВЕРКИ", font=font(16, True), fill="#81e5cb")
    d.text((128, 972), footer, font=font(19), fill="#d5e0ed")
    image.save(OUT / filename)


